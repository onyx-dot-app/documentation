#!/usr/bin/env python3
"""Generate snippets/connector-grid.mdx from the Supported Connectors nav in docs.json.

Each connector becomes one tile. A nav subgroup (Confluence, Gmail, S3, ...) becomes one
tile that links to its first page, except Microsoft 365, whose product pages are listed
one by one. Run with --check to fail when the snippet is stale.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "snippets" / "connector-grid.mdx"
EXPAND_GROUPS = {"Microsoft 365"}
SKIP_PAGES = {"admins/connectors/official/microsoft-365/setup"}
TILE_CLASS = (
    "rounded-lg border border-gray-200 dark:border-gray-700 px-3 py-2 text-sm font-medium "
    "text-gray-800 dark:text-gray-200 hover:border-primary dark:hover:border-primary-light no-underline"
)


def title_of(page: str) -> str:
    text = (ROOT / f"{page}.mdx").read_text()
    m = re.search(r'^title:\s*"?([^"\n]+)"?', text, re.M)
    return m.group(1).strip() if m else page.rsplit("/", 1)[-1]


def find_group(node, name):
    if isinstance(node, dict):
        if node.get("group") == name:
            return node
        for v in node.values():
            found = find_group(v, name)
            if found:
                return found
    elif isinstance(node, list):
        for v in node:
            found = find_group(v, name)
            if found:
                return found
    return None


def entries():
    nav = json.loads((ROOT / "docs.json").read_text())["navigation"]
    group = find_group(nav, "Supported Connectors")
    out = []
    for item in group["pages"]:
        if isinstance(item, str):
            out.append((title_of(item), item))
        elif item["group"] in EXPAND_GROUPS:
            for page in item["pages"]:
                if page not in SKIP_PAGES:
                    out.append((title_of(page), page))
        else:
            out.append((item["group"], item["pages"][0]))
    return sorted(out, key=lambda e: e[0].lower())


def render():
    lines = [
        "{/* Generated by scripts/build_connector_grid.py. Do not edit by hand. */}",
        "",
        '<div className="not-prose grid grid-cols-2 sm:grid-cols-3 md:grid-cols-4 gap-2">',
    ]
    for title, page in entries():
        lines.append(f'  <a href="/{page}" className="{TILE_CLASS}">{title}</a>')
    lines += ["</div>", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    content = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != content:
            print(f"{OUT.relative_to(ROOT)} is stale; run scripts/build_connector_grid.py")
            sys.exit(1)
        sys.exit(0)
    OUT.write_text(content)
    print(f"wrote {OUT.relative_to(ROOT)} ({content.count('<a href')} connectors)")
